"""Exercise real collectors/boundaries with Windows and POSIX path semantics.

These are controlled path tests on the host, not native Windows render evidence.
No reference artwork, audio or finished video is generated by this suite.
"""
from contextlib import contextmanager
from pathlib import Path, PurePosixPath, PureWindowsPath
from types import SimpleNamespace
from unittest.mock import patch
import importlib.util
import json
import os
import shutil
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]

def load_module(name,path):
    spec=importlib.util.spec_from_file_location(name,path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    return module

runtime=load_module('b6_resource_path_runtime',ROOT/'scripts/b6_production.py')
legacy=load_module('b6_resource_path_legacy',ROOT/'assets/b6/hong-kong-v90/run.py')

class WindowsPath(PureWindowsPath):
    def resolve(self):return self

class PosixPath(PurePosixPath):
    def resolve(self):return self

PLATFORMS=((WindowsPath,'C:/new-b6-story'),(PosixPath,'/new-b6-story'))

@contextmanager
def collectors(path_type,root,scoped=False):
    """Keep collector source intact, substitute only host paths/hook registration."""
    callbacks=[];base=path_type(root)
    fake_sys=SimpleNamespace(prefix='',base_prefix='',path=[],addaudithook=callbacks.append)
    with patch.object(legacy,'Path',path_type),patch.object(legacy,'sys',fake_sys):
        reads,outside=legacy.resource_audit(base)
        if scoped:
            roles=runtime.asset_roles()
            with patch.object(roles,'Path',path_type),patch.object(roles,'sys',fake_sys):
                scope=roles.actual_reads_scope(base,reads,'production')
                with scope(),patch.object(runtime,'Path',path_type):yield base,reads,callbacks
        else:
            with patch.object(runtime,'Path',path_type):yield base,reads,callbacks
        assert not outside

def opened(callbacks,path,mode='rb'):
    for callback in callbacks:callback('open',(str(path),mode,0))

class ResourcePaths(unittest.TestCase):
    def test_mandatory_caption_font_and_nested_original_art_match_declarations(self):
        standard=json.loads((ROOT/'assets/b6/style-standard.json').read_text())
        font=standard['public_caption_profiles']['archivo-black']['9:16']['font_file']
        self.assertEqual(font,'fonts/ArchivoBlack.ttf')
        declared=[font,'art/street/new-world.png']
        for path_type,root in PLATFORMS:
            with self.subTest(platform=path_type.__name__),collectors(path_type,root) as (base,reads,hooks):
                for rel in declared:opened(hooks,base/rel)
                # The unchanged historical collector really supplies native keys.
                self.assertEqual(reads,{str(path_type(rel)) for rel in declared})
                observed=runtime.check_resource_reads(reads,dict.fromkeys(declared,'sha'),path_type('outputs/preview-01'))
                self.assertEqual(observed,set(declared))

    def test_scoped_readwrite_character_assets_match_native_generated_keys(self):
        declared=['characters/new-person/side/body.png','characters/new-person/side/cuff.png']
        for path_type,root in PLATFORMS:
            with self.subTest(platform=path_type.__name__),collectors(path_type,root,scoped=True) as (base,reads,hooks):
                # The frozen collector omits r+b; the current scoped collector
                # must still contribute these real reads to the same boundary.
                for rel in declared:opened(hooks,base/rel,'r+b')
                self.assertEqual(reads,{str(path_type(rel)) for rel in declared})
                inputs={str(path_type(rel)):'sha' for rel in declared}
                self.assertEqual(runtime.check_resource_reads(reads,inputs,path_type('outputs/preview-01')),set(declared))

    def test_engine_and_only_the_current_output_subtree_remain_excluded(self):
        paths=['engine/scene.py','engine/source/fonts/ArialBlack.ttf',
               'outputs/preview-01/intermediate/readback.png']
        for path_type,root in PLATFORMS:
            with self.subTest(platform=path_type.__name__),collectors(path_type,root) as (base,reads,hooks):
                for rel in paths:opened(hooks,base/rel)
                self.assertEqual(runtime.check_resource_reads(reads,{},path_type('outputs/preview-01')),set(paths))

    def test_undeclared_art_and_similarly_named_prefixes_still_fail(self):
        for path_type,root in PLATFORMS:
            for rel in ['art/street/unlisted.png','engine-copy/scene.py',
                        'outputs/preview-01-copy/readback.png','outputs/another-preview/readback.png']:
                with self.subTest(platform=path_type.__name__,path=rel),collectors(path_type,root) as (base,reads,hooks):
                    opened(hooks,base/rel)
                    with self.assertRaisesRegex(ValueError,'Declare project-local code/art dependencies') as error:
                        runtime.check_resource_reads(reads,{'art/street/declared.png':'sha'},path_type('outputs/preview-01'))
                    self.assertIn(rel,str(error.exception))

    def test_posix_literal_backslash_names_do_not_alias_declared_slash_paths(self):
        literal='art\\street\\world.png';declared='art/street/world.png'
        with collectors(PosixPath,'/new-b6-story') as (base,reads,hooks):
            opened(hooks,base/literal)
            self.assertNotEqual(runtime.resource_key(literal),runtime.resource_key(declared))
            with self.assertRaisesRegex(ValueError,'Declare project-local code/art dependencies'):
                runtime.check_resource_reads(reads,{declared:'sha'},PosixPath('outputs/preview-01'))
            self.assertEqual(runtime.check_resource_reads(reads,{literal:'sha'},PosixPath('outputs/preview-01')),{literal})

    @unittest.skipIf(os.name=='nt','POSIX literal backslash filenames are not Windows filenames')
    def test_posix_literal_backslash_read_still_checks_its_real_protected_bytes(self):
        roles=runtime.asset_roles()
        with tempfile.TemporaryDirectory(prefix='b6-literal-path-') as tmp:
            base=Path(tmp);(base/'art').mkdir()
            (base/'art/world.png').write_bytes(b'Original unit input; not a finished artwork')
            literal='art\\world.png'
            shutil.copyfile(ROOT/'assets/b6/paint/paris-panorama.png',base/literal)
            with collectors(PosixPath,str(base)) as (fake_base,reads,hooks):
                opened(hooks,fake_base/literal)
                source=[runtime.resource_key(rel) for rel in reads]
                with self.assertRaisesRegex(ValueError,'Protected B6 reference/example/test media'):
                    roles.audit_inputs(base,source,'production')

if __name__=='__main__':unittest.main()
