import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {initB6,runB6} from '../scripts/b6-dynamic-meme.mjs';
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'b6-production-'));
after(()=>fs.rmSync(tmp,{recursive:true,force:true}));
const read=f=>JSON.parse(fs.readFileSync(f,'utf8'));

test('normal B6 init carries the mature engine, leaves both native plans unapproved, and refuses a placeholder film',async()=>{
  const dir=path.join(tmp,'new-brief');initB6(dir,'both');
  const p=read(path.join(dir,'project.json'));
  assert.equal(p.renderer,'b6-production-v1');assert.equal(p.purpose,'production');assert(fs.existsSync(path.join(dir,'b6_asset_roles.py')));assert.equal(p.stage,'needs_authoring');
  const provenance=read(path.join(dir,'engine/font-provenance.json'));
  const licenseByFont={'NotoSans.ttf':'source/fonts/OFL-NotoSans.txt','Nunito.ttf':'source/fonts/OFL-Nunito.txt'};
  const licenses=new Set(provenance.fonts.filter(row=>row.kind==='open-fallback').map(row=>licenseByFont[row.fallback_font]));
  assert(!licenses.has(undefined));
  const engineFiles=read(path.join(dir,'engine/manifest.json')).files;
  assert.equal(Object.keys(engineFiles).length,89+licenses.size);
  for(const rel of licenses)assert(engineFiles[rel]&&fs.existsSync(path.join(dir,'engine',rel)));
  assert(fs.existsSync(path.join(dir,'engine/source/work/hk-v90-unified-arms/rig.py')));
  assert(fs.existsSync(path.join(dir,'engine/font-provenance.json')));
  assert(!fs.existsSync(path.join(dir,'paint')),'must not initialize the old simplified renderer');
  assert.notDeepEqual(read(path.join(dir,p.formats['16:9'])),read(path.join(dir,p.formats['9:16'])));
  await assert.rejects(runB6('preview',[dir,'--ratio','16:9','--trusted-code']),/must author/);
  assert(!fs.existsSync(path.join(dir,'outputs')));
  assert(!fs.existsSync(path.join(dir,'approval-16x9.json')));
  assert(fs.existsSync(path.join(dir,'motion_review.py')));
  assert(fs.existsSync(path.join(dir,'b6_space.py')));
  assert(fs.existsSync(path.join(dir,'caption_renderer.py')));
  assert.equal(p.version,2);
  assert(fs.existsSync(path.join(dir,'b6_puppet.py')));
  assert.deepEqual(p.character_system,{schema:'b6-character-system/1',registry:'characters.json'});
  assert.deepEqual(read(path.join(dir,'characters.json')),{schema:'b6-character-registry/1',actors:[],rigid_cast:[]});
  assert(p.inputs.includes('caption_renderer.py'));
  const portrait=read(path.join(dir,p.formats['9:16']));
  assert.deepEqual(portrait.cast_inventory,[]);
  assert.equal(portrait.caption.font_size,47);assert.equal(portrait.caption.stroke,4);
  assert.equal(portrait.caption.baseline,914);assert.deepEqual(portrait.caption.band,[864,951]);
  assert.equal(portrait.caption.anchor,'ms');assert.equal(portrait.caption.side,44);
  assert.equal(portrait.caption.fill,'#ffffff');assert.equal(portrait.caption.stroke_fill,'#171319');
  assert.equal(portrait.caption.supersampling,3);assert.equal(portrait.caption.resample,'lanczos');
  assert.equal(portrait.caption.pop,false);assert.equal(portrait.caption.autoshrink,false);
  assert(!('bottom' in portrait.caption));
  assert.equal(p.caption_font_variant,'archivo-black');
  assert(p.inputs.includes('fonts/ArchivoBlack.ttf'));assert(p.inputs.includes('fonts/OFL-ArchivoBlack.txt'));
  assert.equal(portrait.caption.profile,'eiffel-v44-portrait-archivo-black-v1');
  assert.equal(portrait.caption.font_family,'Archivo Black');assert.equal(portrait.caption.font_file,'fonts/ArchivoBlack.ttf');
  assert.equal(portrait.caption.font_sha256,'dd9a89a019b4849f66ab75455fe7bdf931311042cbb0f0f97acc061539703180');
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(dir,portrait.caption.font_file))).digest('hex'),portrait.caption.font_sha256);
  assert(!fs.existsSync(path.join(dir,'engine/source/fonts/ArchivoBlack.ttf')));
  const landscape=read(path.join(dir,p.formats['16:9']));
  assert.equal(landscape.caption.profile,'b6-landscape-native-archivo-black-v1');assert.equal(landscape.caption.baseline,620);
  assert.equal(landscape.caption.native_layout_reason,'');
  const target=read(path.join(dir,p.quality_target));
  assert(fs.existsSync(path.join(dir,target.reference.path)));
  assert.equal(target.reference.id,'sample-1-eiffel-portrait-v44');
  assert.equal(target.reference.ratio,'9:16');
  assert.equal(target.preferred_ratio,'9:16');
  assert.equal(target.caption_profiles['9:16'].font_family,'Arial Black');
  assert.equal(target.caption_profiles['9:16'].font_sha256,'7d7db3ad96a31373c1437c6ab14266f6605495544c8e663558b047521174c42e');
  assert.deepEqual(portrait.caption,target.public_caption_profiles['archivo-black']['9:16']);
  assert.equal(target.public_caption_profile_policy.default_new_story_variant,'archivo-black');
  assert.equal(target.reference.sha256,'b0047f5889a7ca1fd47097d8c8b3db054ef412e2f4a7297d3fe04fc1083e5d79');
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(dir,target.reference.path))).digest('hex'),target.reference.sha256);
  assert(target.required_checks.includes('limb_line_weight'));
  assert.equal(Object.values(target.required_subchecks).flat().length,35);
  assert.equal(target.version,3);
  assert.deepEqual(target.acceptance_contract.mandatory_capabilities,['space_depth','body_action']);
  assert(target.acceptance_contract.failure_action.includes('fresh encoding and review'));
  assert(target.style_standard.space_richness);
  assert(target.style_standard.performance);
  assert(target.regressions.length>0);
  assert(target.style_standard.limb_line_weight);
  assert(target.reference.segments.some(s=>s.purpose.includes('Spatial')));
  // Review commands reach production validation instead of falling back or Unknown command.
  await assert.rejects(runB6('review-pack',[dir,'--ratio','16:9','--report','outputs/preview/report.json']),/must author/);
  await assert.rejects(runB6('check-review',[dir,'--ratio','16:9','--review','outputs/review/motion-review.json']),/must author/);
  // Validation must not import untrusted authored scene code.
  fs.writeFileSync(path.join(dir,'scene.py'),'raise RuntimeError("must not import")\n');
  const r=spawnSync('python3',[path.join(dir,'run.py'),'validate',dir,'--ratio','16:9'],{encoding:'utf8'});
  assert.notEqual(r.status,0);assert(!r.stderr.includes('must not import'));
});
